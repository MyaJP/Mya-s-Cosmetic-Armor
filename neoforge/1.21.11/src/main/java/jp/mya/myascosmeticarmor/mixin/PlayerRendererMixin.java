package jp.mya.myascosmeticarmor.mixin;

import jp.mya.myascosmeticarmor.client.RenderSwap;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
import net.minecraft.client.renderer.entity.player.AvatarRenderer;
import net.minecraft.client.renderer.entity.state.AvatarRenderState;
import net.minecraft.world.entity.Avatar;

/** プレイヤーを描く間だけ、防具を見た目の防具に差し替える */
@Mixin(AvatarRenderer.class)
public abstract class PlayerRendererMixin {
    @Inject(method = "extractRenderState(Lnet/minecraft/world/entity/Avatar;Lnet/minecraft/client/renderer/entity/state/AvatarRenderState;F)V", at = @At("HEAD"))
    private void myas_cosmetic_armor$before(Avatar entity, AvatarRenderState state, float partialTick, CallbackInfo ci) {
        RenderSwap.before(entity);
    }

    @Inject(method = "extractRenderState(Lnet/minecraft/world/entity/Avatar;Lnet/minecraft/client/renderer/entity/state/AvatarRenderState;F)V", at = @At("RETURN"))
    private void myas_cosmetic_armor$after(Avatar entity, AvatarRenderState state, float partialTick, CallbackInfo ci) {
        RenderSwap.after();
    }
}
