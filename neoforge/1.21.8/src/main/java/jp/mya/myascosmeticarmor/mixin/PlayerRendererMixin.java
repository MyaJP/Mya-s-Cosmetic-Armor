package jp.mya.myascosmeticarmor.mixin;

import jp.mya.myascosmeticarmor.client.RenderSwap;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
import net.minecraft.client.player.AbstractClientPlayer;
import net.minecraft.client.renderer.entity.player.PlayerRenderer;
import net.minecraft.client.renderer.entity.state.PlayerRenderState;

/** プレイヤーを描く間だけ、防具を見た目の防具に差し替える */
@Mixin(PlayerRenderer.class)
public abstract class PlayerRendererMixin {
    @Inject(method = "extractRenderState(Lnet/minecraft/client/player/AbstractClientPlayer;Lnet/minecraft/client/renderer/entity/state/PlayerRenderState;F)V", at = @At("HEAD"))
    private void myas_cosmetic_armor$before(AbstractClientPlayer entity, PlayerRenderState state, float partialTick, CallbackInfo ci) {
        RenderSwap.before(entity);
    }

    @Inject(method = "extractRenderState(Lnet/minecraft/client/player/AbstractClientPlayer;Lnet/minecraft/client/renderer/entity/state/PlayerRenderState;F)V", at = @At("RETURN"))
    private void myas_cosmetic_armor$after(AbstractClientPlayer entity, PlayerRenderState state, float partialTick, CallbackInfo ci) {
        RenderSwap.after();
    }
}
